"""Write a Fast DDS XML profile for the HIL link, with this host's interface and its peers filled in.

    python3 tools/dds_profile.py --iface enp5s0 --peers 192.168.9.2,192.168.9.3 --out config/dds/fastdds_hil.xml
    UW_HIL_IFACE=enp5s0 UW_HIL_PEERS=192.168.9.2 python3 tools/dds_profile.py --out config/dds/fastdds_hil.xml
    python3 tools/dds_profile.py --loopback --out config/dds/fastdds_gt.xml      # the ground-truth participant

Why a generator and not a file in the repo: the profile is **per host** — the interface whitelist carries that
host's own address and the peer list carries the others' — so a committed XML would be either wrong on two of the
three machines or a merge conflict. The rendered files are gitignored for the same reason that
`config/runtime.local.yaml` is. `docs/bridge_setup.md` §4 explains what each element is for.

What the profile does, and why each part is there (all three parts are needed before the link leaves the host):

- **UDPv4 only, `useBuiltinTransports` false.** Fast DDS enables shared memory by default, which works only
  within one machine; NVIDIA's own multi-machine instruction is a single UDPv4 transport. Without it,
  participants discover each other and no data arrives, which is the most-reported Isaac-to-another-host symptom.
- **`receiveBufferSize`** well above the default 212992: a 1.79 MB sample is ~1200 IP fragments at MTU 1500 and
  one lost fragment drops the whole sample. Measured, BEST_EFFORT: 6 of 250 lost with the default, 0 with 4 MB
  (docs/bridge_setup.md §6.1). It is capped by `net.core.rmem_max`, which `config/sysctl/60-ros2-hil.conf` pins.
- **`interfaceWhiteList`** with one address: it keeps Fast DDS off every other interface this box has — on linus
  that is `virbr0`, `docker0`, two bridges and `tailscale0`, and on Windows the Hyper-V and WSL adapters, which
  is the usual cause of "it only discovers its own nodes".
- **`initialPeersList`**, only when peers are given: explicit unicast discovery for when multicast does not
  work. A peer with no port probes only the first few participant ids on that host
  (`maxInitialPeersRange`), which is the usual cause of "it discovers *some* of the nodes", so each peer is
  written with the metatraffic unicast port of the domain as well.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

#: Fast DDS port algorithm: port = PB + DG * domain + offset, with offset d1 = 10 + 2 * participant_id for
#: unicast metatraffic (docs/bridge_setup.md §3)
PORT_BASE, DOMAIN_GAIN, METATRAFFIC_UNICAST, PARTICIPANT_GAIN = 7400, 250, 10, 2

TEMPLATE = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by tools/dds_profile.py — do not edit; it is per host and gitignored.
     host interface: {iface}{peers_note}
     domain {domain}: metatraffic multicast {mc_port}, unicast {uc_port}+2n (group 239.255.0.1) -->
<dds xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <profiles>
    <transport_descriptors>
      <transport_descriptor>
        <transport_id>uw_udp</transport_id>
        <type>UDPv4</type>
        <sendBufferSize>{send_buf}</sendBufferSize>
        <receiveBufferSize>{recv_buf}</receiveBufferSize>
        <maxMessageSize>65500</maxMessageSize>
        <interfaceWhiteList>
          <address>{iface}</address>
        </interfaceWhiteList>
      </transport_descriptor>
    </transport_descriptors>

    <participant profile_name="uw_hil" is_default_profile="true">
      <rtps>
        <userTransports><transport_id>uw_udp</transport_id></userTransports>
        <useBuiltinTransports>false</useBuiltinTransports>
        <builtin>
{discovery}        </builtin>
      </rtps>
    </participant>
  </profiles>
</dds>
"""

UNICAST = """          <metatrafficUnicastLocatorList>
            <locator><udpv4><address>{iface}</address></udpv4></locator>
          </metatrafficUnicastLocatorList>
          <initialPeersList>
{peers}          </initialPeersList>
"""
PEER = """            <locator><udpv4><address>{ip}</address><port>{port}</port></udpv4></locator>
"""
# a double hyphen is not allowed inside an XML comment, so no option names in here
MULTICAST = """          <!-- multicast discovery (Fast DDS default, group 239.255.0.1). Pass peers to replace
               it with explicit unicast locators when a switch or a routed path blocks multicast. -->
"""

IPV4 = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")


def iface_address(name_or_ip: str) -> str:
    """An IPv4 address, from an address or from an interface name (`ip -4 -o addr show dev NAME`)."""
    if IPV4.match(name_or_ip):
        return name_or_ip
    if not shutil.which("ip"):
        raise SystemExit(f"dds_profile: {name_or_ip!r} is not an IPv4 address and iproute2 is not installed here; "
                         f"pass the address itself")
    out = subprocess.run(["ip", "-4", "-o", "addr", "show", "dev", name_or_ip], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit(f"dds_profile: no interface {name_or_ip!r}: {out.stderr.strip()}")
    found = re.search(r"\binet (\d+\.\d+\.\d+\.\d+)", out.stdout)
    if not found:
        raise SystemExit(f"dds_profile: interface {name_or_ip!r} has no IPv4 address")
    return found.group(1)


def profile(iface: str, peers: list[str], domain: int, recv_buf: int, send_buf: int,
            peer_participants: int = 4) -> str:
    """The XML. ``peers`` empty: multicast discovery. ``peer_participants``: how many participant ids to probe
    per peer, since a peer locator without a port probes only the first few."""
    uc_port = PORT_BASE + DOMAIN_GAIN * domain + METATRAFFIC_UNICAST
    if peers:
        locators = "".join(PEER.format(ip=ip, port=uc_port + PARTICIPANT_GAIN * n)
                           for ip in peers for n in range(max(peer_participants, 1)))
        discovery = UNICAST.format(iface=iface, peers=locators)
    else:
        discovery = MULTICAST
    return TEMPLATE.format(iface=iface, domain=domain, send_buf=send_buf, recv_buf=recv_buf,
                           mc_port=PORT_BASE + DOMAIN_GAIN * domain, uc_port=uc_port, discovery=discovery,
                           peers_note="" if not peers else f"; peers: {', '.join(peers)}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="tools/dds_profile.py", description=__doc__.splitlines()[0])
    ap.add_argument("--iface", default=os.environ.get("UW_HIL_IFACE", ""),
                    help="this host's HIL interface: an IPv4 address or an interface name (env UW_HIL_IFACE)")
    ap.add_argument("--peers", default=os.environ.get("UW_HIL_PEERS", ""),
                    help="comma-separated peer addresses for unicast discovery (env UW_HIL_PEERS); "
                         "empty leaves multicast discovery in place")
    ap.add_argument("--loopback", action="store_true",
                    help="a profile for the ground-truth participant and its bag: 127.0.0.1 only, so it cannot "
                         "reach the HIL interface at all")
    ap.add_argument("--domain", type=int, default=int(os.environ.get("UW_ROS_DOMAIN_ID", "73")),
                    help="only used for the peer ports and the comment (default: UW_ROS_DOMAIN_ID, else 73)")
    ap.add_argument("--recv-buf", type=int, default=int(os.environ.get("UW_DDS_RECV_BUF", 4 << 20)))
    ap.add_argument("--send-buf", type=int, default=int(os.environ.get("UW_DDS_SEND_BUF", 1 << 20)))
    ap.add_argument("--out", default="-", help="output file, or - for stdout")
    args = ap.parse_args(argv)

    if args.loopback:
        iface, peers = "127.0.0.1", []
    else:
        if not args.iface:
            ap.error("--iface (or UW_HIL_IFACE): this host's HIL interface, by address or name")
        iface = iface_address(args.iface)
        peers = [p.strip() for p in args.peers.split(",") if p.strip()]
        for p in peers:
            if not IPV4.match(p):
                ap.error(f"--peers wants IPv4 addresses, got {p!r}")
    text = profile(iface, peers, args.domain, args.recv_buf, args.send_buf)
    if args.out == "-":
        sys.stdout.write(text)
    else:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"{out}: interface {iface}, {len(peers) or 'multicast'} "
              f"{'peers' if peers else 'discovery'}, recv buffer {args.recv_buf // 1024} kB", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
