"""Index the DeeperSense metadatabase (Zenodo 10373154, CC BY 4.0) to pick the recordings worth requesting.

    python tools/deepersense_index.py ~/underwater_data/real/deepersense_metadata [--location dfki_basin]
                                      [--sensor sonar-oculus] [--out docs/deepersense_tank_recordings.md]

The record holds metadata only: the sensor data itself is released on demand by DFKI. Only the ROS bags carry the
raw polar beam data; the published image datafiles are a Cartesian projection (`modality.modality_description`),
so a request should always name bags. Reads the CSV export, not metadata.sqlite, so that nothing has to be
unpacked beyond `csv.zip`. Writes a Markdown table and prints the aggregate the request needs.
"""
import argparse
import ast
import collections
import csv
from pathlib import Path

csv.field_size_limit(10 ** 9)
CONFIG_KEYS = ("freqMode", "range", "gain", "pingRate", "gamma", "data_16bit", "send_gain", "gain_assistance")


def read(root: Path, name: str) -> list:
    with (root / "csv" / name).open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def index(root: Path, location: str, sensor: str) -> list:
    loc = {r["location_id"]: r for r in read(root, "location.csv")}
    ses = {r["session_id"]: r for r in read(root, "session.csv")}
    dat = {r["dataset_id"]: r for r in read(root, "dataset.csv")}
    sen = {r["sensor_id"]: r for r in read(root, "sensor.csv")}
    log = {r["logfile_id"]: r for r in read(root, "logfile.csv")}
    rows = []
    for s in read(root, "stream.csv"):
        if sen[s["sensor_id"]]["sensor_key"] != sensor:
            continue
        d = dat[s["dataset_id"]]
        session = ses[d["session_id"]]
        if loc[session["location_id"]]["location_key"] != location:
            continue
        lf = log[s["logfile_id"]]
        cfgs = ast.literal_eval(s["sensor_configuration"]) if s["sensor_configuration"] else [{}]
        rows.append({"session": session["session_key"], "dataset": d["dataset_key"],
                     "start": d["dataset_start"][:19], "duration_s": float(s["stream_duration"]),
                     "bag": lf["logfile_path"], "bag_bytes": int(lf["logfile_size"]),
                     "pings": int(s["num_ros_messages"]), "objects": d["objects"],
                     "visibility": d["visibility"], "configs": cfgs})
    rows.sort(key=lambda r: r["start"])
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("root", type=Path, help="directory holding the unpacked csv/ of the Zenodo record")
    ap.add_argument("--location", default="dfki_basin", help="location_key (dfki_basin is the lab tank)")
    ap.add_argument("--sensor", default="sonar-oculus", help="sensor_key")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    rows = index(args.root, args.location, args.sensor)
    if not rows:
        raise SystemExit(f"no {args.sensor} streams at {args.location}")
    agg = collections.defaultdict(collections.Counter)
    for r in rows:
        for c in r["configs"]:
            for k in CONFIG_KEYS:
                agg[k][c.get(k)] += 1
    total_h = sum(r["duration_s"] for r in rows) / 3600
    total_gb = sum(r["bag_bytes"] for r in rows) / 1e9
    print(f"{len(rows)} {args.sensor} streams at {args.location}: {total_h:.2f} h, {total_gb:.1f} GB of bags")
    for k in CONFIG_KEYS:
        print(f"  {k}: {dict(agg[k].most_common())}")
    # 16-bit samples, or the per-row gain sent alongside them, are what makes a bag quantitatively usable.
    best = [r for r in rows if any(c.get("data_16bit") == "True" or c.get("send_gain") == "True" for c in r["configs"])]
    print(f"\n{len(best)} of them send 16-bit samples or the per-row gain "
          f"({sum(r['bag_bytes'] for r in best) / 1e9:.1f} GB):")
    for r in best:
        flags = ",".join(sorted({f"16bit={c.get('data_16bit')} gain_sent={c.get('send_gain')}" for c in r["configs"]}))
        print(f"  {r['bag']}  {r['bag_bytes'] / 1e9:.2f} GB  {r['duration_s']:.0f} s  {flags}")
    if args.out:
        head = (f"# {args.sensor} recordings at {args.location} (DeeperSense, Zenodo 10373154)\n\n"
                f"{len(rows)} streams, {total_h:.2f} h, {total_gb:.1f} GB of bags. Generated by "
                f"`tools/deepersense_index.py`.\n\n"
                "| dataset | start | dur [s] | bag [GB] | pings | freq | range [m] | gain | 16 bit | gain sent | objects |\n"
                "|---|---|---|---|---|---|---|---|---|---|---|\n")
        pick = lambda r, k: "/".join(sorted({str(c.get(k)) for c in r["configs"]}))     # noqa: E731
        body = "".join(
            f"| {r['dataset']} | {r['start'][:16]} | {r['duration_s']:.0f} | {r['bag_bytes'] / 1e9:.2f} | "
            f"{r['pings']} | {pick(r, 'freqMode')} | {pick(r, 'range')} | {pick(r, 'gain')} | "
            f"{pick(r, 'data_16bit')} | {pick(r, 'send_gain')} | {r['objects'][:60]} |\n" for r in rows)
        args.out.write_text(head + body + "\nfreq: Oculus `freqMode`, 1 = low, 2 = high.\n")
        print(f"\n-> {args.out}")


if __name__ == "__main__":
    main()
